use p2_lia_spike::{
    fixtures,
    search::{solve, Budget, Outcome},
};

fn main() {
    let mut lean =
        String::from("-- Generated by the independent Rust search.\nimport P2\nopen P2\n\n");
    println!("| example | result | branches | digits | generated | certificate bytes charged/final | operations | rounds | integer splits | peak rows | wall µs |\n|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
    for (name, f, unsat) in fixtures::examples() {
        let start = std::time::Instant::now();
        let report = solve(&f, Budget::default());
        let elapsed = start.elapsed().as_micros();
        let (result, actual) = match &report.outcome {
            Outcome::Proved(c) => {
                assert!(unsat, "unexpected proof: {name}");
                lean.push_str(&format!("def {name}_input : Formula := {}\ndef {name}_cert : Cert := {}\n#guard check {name}_input {name}_cert\n\n",f.lean(),c.lean()));
                ("proved".to_string(), c.wire_bytes())
            }
            Outcome::Model(m) => {
                assert!(!unsat, "unexpected model: {name}: {m:?}");
                (format!("model {m:?}"), 0)
            }
            Outcome::Unknown(e) => panic!("representative example {name} exhausted: {e:?}"),
        };
        let s = &report.stats;
        println!(
            "| {name} | {result} | {} | {} | {} | {}/{} | {} | {} | {} | {} | {elapsed} |",
            s.branches,
            s.max_digits,
            s.generated,
            s.certificate_bytes,
            actual,
            s.operations,
            s.rounds,
            s.integer_splits,
            s.peak_rows
        );
    }
    let budget = Budget {
        generated: 128,
        ..Budget::default()
    };
    let report = solve(&fixtures::explosion(16), budget);
    let Outcome::Unknown(e) = report.outcome else {
        panic!("explosion did not stop")
    };
    assert_eq!(e.resource, "generated");
    let s = report.stats;
    println!(
        "| explosion_16 | unknown {} {}/{} | {} | {} | {} | {}/— | {} | {} | {} | {} | — |",
        e.resource,
        e.used,
        e.limit,
        s.branches,
        s.max_digits,
        s.generated,
        s.certificate_bytes,
        s.operations,
        s.rounds,
        s.integer_splits,
        s.peak_rows
    );
    for m in [4, 8, 16] {
        let budget = Budget {
            generated: 512,
            ..Budget::default()
        };
        let start = std::time::Instant::now();
        let report = solve(&fixtures::layered_explosion(m), budget);
        let elapsed = start.elapsed().as_micros();
        let result = match report.outcome {
            Outcome::Model(_) => "validated model".to_string(),
            Outcome::Unknown(e) => format!("unknown {} {}/{}", e.resource, e.used, e.limit),
            Outcome::Proved(_) => panic!("zero is a model of layered explosion"),
        };
        let s = report.stats;
        println!(
            "| layered_{m} | {result} | {} | {} | {} | {}/— | {} | {} | {} | {} | {elapsed} |",
            s.branches,
            s.max_digits,
            s.generated,
            s.certificate_bytes,
            s.operations,
            s.rounds,
            s.integer_splits,
            s.peak_rows
        );
    }
    if let Some(path) = std::env::args().nth(1) {
        std::fs::write(path, lean).expect("write generated Lean replay");
    }
}
